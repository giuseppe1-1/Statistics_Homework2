function runAttack() {
  if (!model) return;
  const text = $("atkCipher").value, c = toIdx(lettersOnly(text));
  if (!c.length) { $("atkRes").innerHTML = "<tr><td>Enter a ciphertext containing letters.</td></tr>"; $("candTab").innerHTML = ""; return; }
  const S = scoreAll(c, model, CORPUS[curLang()].words);
  let h = "<tr><th>Method</th><th>Key</th><th>Decryption</th></tr>";
  METHODS.forEach(m => {
    const ties = argmaxAll(S[m.id]);
    h += `<tr><td>${m.name}</td><td class="m">${ties[0]}${ties.length > 1 ? " <span class='bad' title='tie'>(" + ties.length + " tied)</span>" : ""}</td><td class="pv">${esc(caesar(text, -ties[0]))}</td></tr>`;
  });
  $("atkRes").innerHTML = h + `<tr><td colspan="3" class="sub">${c.length} letters analysed. A &ldquo;tied&rdquo; result means the method cannot tell the keys apart.</td></tr>`;
  // candidate table
  const mid = $("candMethod").value || "bi", sc = S[mid];
  const order = [...Array(26).keys()].sort((a, b) => sc[b] - sc[a]);
  let t = "<tr><th>#</th><th>Key</th><th>Score</th><th>Decryption</th></tr>";
  order.forEach((s, i) => { t += `<tr class="${i === 0 ? "best" : ""}"><td>${i + 1}</td><td class="m">${s}</td><td class="m">${sc[s].toFixed(mid === "top" || mid === "dic" ? 0 : 1)}</td><td class="pv">${esc(caesar(text, -s))}</td></tr>`; });
  $("candTab").innerHTML = t;
  const mname = METHODS.find(m => m.id === mid).name;
  $("atkPlain").textContent = caesar(text, -order[0]);
  $("atkPlainLabel").textContent = "Recovered original text: ciphertext decrypted with the key found by \u201c" + mname + "\u201d (key " + order[0] + ")";
  // chart: ciphertext counts and expected counts under the best key
  const best = order[0], cnt = new Array(26).fill(0);
  c.forEach(v => cnt[v]++);
  const marks = cnt.map((_, j) => c.length * model.p[(j - best + 26) % 26]);
  barChart($("atkChart"), cnt, { labels: ABC.split(""), every: 1, marks });
}

