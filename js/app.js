/* ---------- formatting ---------- */
const fmtCoord = (c, v) => c.bytes === 1 ? v.toString() : "0x" + v.toString(16).padStart(c.bytes * 2, "0");
const fmtPt = (c, P) => P ? "(" + fmtCoord(c, P[0]) + ", " + fmtCoord(c, P[1]) + ")" : "point at infinity";
const fmtN = v => Number(v).toLocaleString("en-US");
const fmtBig = v => v < 10n ** 15n ? Number(v).toLocaleString("en-US") : v.toString();
function fmtMs(ms) { return ms < 1000 ? ms.toFixed(0) + " ms" : (ms / 1000).toFixed(2) + " s"; }
function fmtTime(sec) {
  if (sec < 1e-3) return "< 1 ms";
  if (sec < 1) return (sec * 1000).toFixed(0) + " ms";
  if (sec < 60) return sec.toFixed(1) + " s";
  if (sec < 3600) return (sec / 60).toFixed(1) + " min";
  if (sec < 86400) return (sec / 3600).toFixed(1) + " h";
  if (sec < 3.156e7) return (sec / 86400).toFixed(1) + " days";
  const y = sec / 3.156e7;
  return y < 1e6 ? y.toFixed(1) + " years" : y.toExponential(1).replace(/e\+(\d+)/, "·10<sup>$1</sup>") + " years";
}
const sci = x => x < 1e6 ? fmtN(Math.round(x)) : x.toExponential(1).replace(/e\+(\d+)/, "·10<sup>$1</sup>");

/* ---------- section 1: ECC ---------- */
function range() { return keyRange(st.c, st.bits); }
function updRangeInfo() {
  const c = st.c, r = range();
  $("bits").disabled = c.id === "toy17";
  if (c.id === "toy17") {
    $("rangeInfo").innerHTML = `Group of <b>order n = ${c.n}</b> generated by G = (1, 5): private keys can only be 1..${c.n - 1n}. The tiny field makes the whole scheme trivially breakable.`;
  } else {
    $("rangeInfo").innerHTML = `Private key in <b>[1, ${fmtBig(r)}]</b> (${st.bits} bits, ${fmtBig(r)} keys). The full group order is n &asymp; 2<sup>256</sup>.`;
  }
}
function setKeys(d) {
  st.d = d;
  st.Q = ecMul(st.c, d, genOf(st.c));
  $("dPriv").value = d.toString();
  let h = fmtPt(st.c, st.Q);
  if (d > range()) h += "\n(d is outside the restricted range, so the attacks of Section 5 would not apply)";
  $("Qout").textContent = h;
  st.enc = null;
  updAtkInfo();
}
function genKeys() { setKeys(randBelow(range())); doEncrypt(); }
function onPrivEdit() {
  try {
    const d = BigInt($("dPriv").value.trim());
    if (d < 1n || d >= st.c.n) throw 0;
    const keep = $("dPriv").value;
    setKeys(d); $("dPriv").value = keep;
  } catch (e) { $("Qout").textContent = "Enter an integer between 1 and n - 1"; st.Q = null; }
}
function onCurveChange() {
  st.c = CURVES[$("curveSel").value];
  if (st.c.id === "secp256k1") st.bits = Math.max(2, Math.min(256, parseInt($("bits").value) || 16));
  updRangeInfo(); genKeys();
}
function onBitsChange() {
  st.bits = Math.max(2, Math.min(256, parseInt($("bits").value) || 16));
  updRangeInfo(); genKeys();
}
function onMsgChange() { if (st.Q) doEncrypt(); }

function doEncrypt() {
  if (!st.Q) { $("encLog").value = "Set a valid private key first."; return; }
  const c = st.c, m = textEnc.encode($("msg").value);
  const r = randBelow(range());
  const e = eccEncrypt(c, st.Q, m, r);
  st.enc = e;
  const L = [];
  L.push("curve: y^2 = x^3 + 7 over F_p" + (c.id === "toy17" ? " with p = 17" : ", p = 2^256 - 2^32 - 977"));
  L.push("G = " + fmtPt(c, genOf(c)));
  L.push("");
  L.push("1. receiver public key Q = dG");
  L.push("   Q = " + fmtPt(c, st.Q));
  L.push("2. sender picks ephemeral r in [1, " + fmtBig(range()) + "]");
  L.push("   r = " + r);
  L.push("3. R = rG = " + fmtPt(c, e.R));
  L.push("4. shared secret S = rQ");
  L.push("   S = " + fmtPt(c, e.S));
  L.push("5. keystream = SHA-256('ECTOY' || S.x || i), i = 0, 1, ...");
  L.push("   first bytes: " + toHex(e.ks.subarray(0, 16)) + (e.ks.length > 16 ? "..." : ""));
  L.push("6. c = m XOR keystream (" + m.length + " bytes)");
  L.push("   m = " + toHex(m.subarray(0, 16)) + (m.length > 16 ? "..." : ""));
  L.push("   c = " + toHex(e.ct.subarray(0, 16)) + (e.ct.length > 16 ? "..." : ""));
  $("encLog").value = L.join("\n");
  $("Rin").value = e.R ? e.R.map(v => fmtCoord(c, v)).join(", ") : "";
  $("ctIn").value = toHex(e.ct);
  $("decOut").textContent = ""; $("decStatus").textContent = "";
  updAtkInfo();
}
function parsePoint(s) {
  const parts = s.split(/[,\s]+/).filter(Boolean);
  if (parts.length !== 2) throw new Error("R must be two numbers: x, y");
  return [BigInt(parts[0]), BigInt(parts[1])];
}
function doDecrypt(tamper) {
  try {
    if (!st.d) throw new Error("no private key");
    const R = parsePoint($("Rin").value);
    if (!onCurve(st.c, R)) { $("decOut").textContent = ""; $("decStatus").innerHTML = '<span class="bad">R is not a point of the curve: rejected.</span>'; return; }
    const ct = fromHex($("ctIn").value);
    if (tamper && ct.length) { ct[0] ^= 1; $("ctIn").value = toHex(ct); }
    const pt = eccDecrypt(st.c, st.d, R, ct);
    $("decOut").textContent = textDec.decode(pt);
    const same = textDec.decode(pt) === $("msg").value;
    $("decStatus").innerHTML = same ? '<span class="ok">Matches the original message.</span>'
      : (tamper ? '<span class="bad">Differs from the original: one ciphertext bit flipped one plaintext bit, and nothing signalled it.</span>' : '<span class="bad">Does not match the original message.</span>');
  } catch (e) { $("decStatus").innerHTML = '<span class="bad">' + esc(String(e.message || e)) + '</span>'; }
}

