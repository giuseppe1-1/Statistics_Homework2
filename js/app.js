async function runEcAttack(which) {
  if (!at.enc) atkEncrypt(true);
  const c = at.c, N = atkRange(), targetIsR = $("atkTarget").value === "R", target = targetIsR ? at.enc.R : at.Q;
  if (at.bits > 32 && c.id !== "toy17") {
    $("ecAtkStatus").innerHTML = `<span class="bad">A ${at.bits}-bit key space is too large for this demo.</span> Reduce the key size (32 bits or less) or see the extrapolation table below.`;
    return;
  }
  if (!target) { $("ecAtkStatus").textContent = "The target is the point at infinity."; return; }
  st.cancel = false; setBusy(true); ecResults = [];
  $("ecAtkPlain").textContent = ""; $("ecAtkStatus").textContent = "Running...";
  const prog = $("prog");
  const jobs = which === "both" ? ["bf", "bsgs"] : [which];
  let found = null;
  for (const j of jobs) {
    prog.style.width = "0%";
    const cb = f => { prog.style.width = (100 * f).toFixed(1) + "%"; };
    const res = j === "bf" ? await bruteForceAttack(c, target, N, cb, () => st.cancel) : await bsgsAttack(c, target, N, cb, () => st.cancel);
    res.name = j === "bf" ? "Exhaustive search" : "Baby-step giant-step";
    res.mem = j === "bf" ? "O(1)" : fmtN(res.table || 0) + " points";
    res.ok = res.k !== null && ecEq(ecMul(c, res.k, genOf(c)), target);
    ecResults.push(res); showEcResults();
    if (res.ok && found === null) found = res.k;
    if (res.cancelled) break;
  }
  prog.style.width = "100%";
  if (found !== null) {
    const mm = ecResults.filter(r => r.name === "Exhaustive search" && r.ok && r.ms > 20)[0];
    if (mm && at.bits >= 8) st.rate = mm.steps / (mm.ms / 1000);
    const pt = targetIsR ? decryptWithSecret(c, ecMul(c, found, at.Q), at.enc.ct) : eccDecrypt(c, found, at.enc.R, at.enc.ct);
    const txt = textDec.decode(pt);
    $("ecAtkPlain").textContent = txt;
    $("ecAtkStatus").innerHTML = (targetIsR ? "Ephemeral key r" : "Private key d") + " = <b>" + found + "</b> recovered " +
      (targetIsR ? "(the shared secret was computed as S = rQ, d was not needed). " : "") +
      (txt === $("atkMsg").value ? '<span class="ok">The message was decrypted correctly.</span>' : "");
    renderExtrap();
  } else {
    $("ecAtkStatus").innerHTML = st.cancel ? "Cancelled." : '<span class="bad">Key not found in the range.</span>';
  }
  setBusy(false);
}

const SCALE_BITS = [8, 10, 12, 14, 16, 18];
async function runScaling() {
  $("scaleMsg").textContent = "Running (about ten seconds)..."; await tick();
  const c = CURVES.secp256k1, G = genOf(c), rows = [];
  for (const b of SCALE_BITS) {
    let sb = 0, tb = 0, ss = 0, ts = 0;
    for (let t = 0; t < 3; t++) {
      const lo = 1n << BigInt(b - 1), d = lo + randBelow(lo), T = ecMul(c, d, G), N = 1n << BigInt(b);
      const r1 = await bruteForceAttack(c, T, N), r2 = await bsgsAttack(c, T, N);
      sb += r1.steps; tb += r1.ms; ss += r2.steps; ts += r2.ms;
    }
    rows.push({ b, sb: sb / 3, tb: tb / 3, ss: ss / 3, ts: ts / 3 });
    await tick();
  }
  let h = "<tr><th>Key bits</th><th>Exhaustive: operations</th><th>time</th><th>BSGS: operations</th><th>time</th></tr>";
  rows.forEach(r => h += `<tr><td class="m">${r.b}</td><td class="m">${fmtN(Math.round(r.sb))}</td><td class="m">${fmtMs(r.tb)}</td><td class="m">${fmtN(Math.round(r.ss))}</td><td class="m">${fmtMs(r.ts)}</td></tr>`);
  $("scaleTab").innerHTML = h; $("scaleTab").style.display = "table"; $("scaleFig").style.display = "block";
  lineChart($("scaleChart"), rows.map(r => r.b), [
    { name: "Exhaustive search", color: "#d62728", values: rows.map(r => Math.log2(r.sb)) },
    { name: "Baby-step giant-step", color: "#3b9de0", values: rows.map(r => Math.log2(r.ss)) }
  ], { ymin: 0, ymax: 20, ticks: 5, xtitle: "private key size (bits)", fmt: v => v.toFixed(0) });
  const last = rows[rows.length - 1];
  st.rate = last.sb / (last.tb / 1000);
  $("scaleMsg").textContent = `Measured speed of the exhaustive search on this machine: about ${fmtN(Math.round(st.rate))} group operations per second.`;
  renderExtrap();
}
