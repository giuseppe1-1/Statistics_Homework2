function runComparison() {
  if (!st.Q) genKeys();
  const text = $("cmpText").value, c = st.c;
  const letters = text.replace(/[^A-Za-z]/g, "").toUpperCase();
  if (letters.length < 100) {
    $("cmpTab").style.display = "none";
    $("cmpMsg").innerHTML = '<span class="bad">Enter at least 100 letters (a few sentences) so that the statistics mean something.</span>';
    return;
  }
  $("cmpMsg").textContent = "";
  const s = ((parseInt($("cmpShift").value) || 0) % 26 + 26) % 26;
  // Caesar
  const cc = caesar(text, s), cl = cc.replace(/[^A-Za-z]/g, "").toUpperCase();
  const pc = new Array(26).fill(0), cnt = new Array(26).fill(0);
  for (const ch of letters) pc[ch.charCodeAt(0) - 65]++;
  for (const ch of cl) cnt[ch.charCodeAt(0) - 65]++;
  const cbytes = textEnc.encode(cc), pbytes = textEnc.encode(text);
  const cbytes2 = textEnc.encode(caesar(text, s + 1));
  const long = pbytes.length >= 1000;
  // ECC
  const r = randBelow(range());
  const e1 = eccEncrypt(c, st.Q, pbytes, r);
  const Q2 = ecMul(c, (st.d % (c.n - 1n)) + 1n, genOf(c)); // key d+1
  const e2 = eccEncrypt(c, Q2, pbytes, r);
  const e3 = eccEncrypt(c, st.Q, pbytes, randBelow(range()));
  const bc = new Array(256).fill(0), pb = new Array(256).fill(0);
  for (const v of e1.ct) bc[v]++;
  for (const v of pbytes) pb[v]++;
  // flip one plaintext bit (case bit of a letter) and see what changes
  const from = Math.min(40, text.length - 1);
  let pos = text.slice(from).search(/[A-Za-z]/);
  pos = pos < 0 ? text.search(/[A-Za-z]/) : pos + from;
  const flipStr = text.slice(0, pos) + String.fromCharCode(text.charCodeAt(pos) ^ 32) + text.slice(pos + 1);
  const cFlip = textEnc.encode(caesar(flipStr, s));
  const flipped = pbytes.slice(); flipped[textEnc.encode(text.slice(0, pos)).length] ^= 32;
  const eFlip = eccEncrypt(c, st.Q, flipped, r);
  const chiE = chi2Uniform(bc);
  const rows = [
    ["Plaintext reference", entropy(pc).toFixed(2) + " bits / letter  (max 4.70)", entropy(pb).toFixed(2) + " bits / byte (text, max 8)"],
    ["Entropy of the ciphertext", entropy(cnt).toFixed(2) + " bits / letter", entropy(bc).toFixed(2) + " bits / byte (about " + (8 - 255 / (2 * pbytes.length * Math.LN2)).toFixed(2) + " expected for random bytes of this length)"],
    ["Index of coincidence", coincidence(cnt).toFixed(4) + "  (random letters: 0.0385, English: about 0.066)", coincidence(bc).toFixed(4) + "  (random bytes: 0.0039)"],
    ["Chi-squared vs uniform", chi2Uniform(cnt).toFixed(0) + "  (25 d.o.f., 5% limit 37.7): " + (chi2Uniform(cnt) > 37.7 ? "far from uniform" : "compatible with uniform"), chiE.toFixed(0) + "  (255 d.o.f., 5% limit about 293): " + (long ? (chiE < 310 ? "compatible with uniform" : "not uniform") : "text too short for a reliable test (use 1,000+ characters)")],
    ["Fraction of 1 bits", onesRatio(cbytes).toFixed(3) + "  (ASCII letters keep fixed high bits)", onesRatio(e1.ct).toFixed(3)],
    ["Change of the key by +1: ciphertext bits that change", (100 * bitDiffRatio(cbytes, cbytes2)).toFixed(1) + " %  (structure is kept, letters just move)", (100 * bitDiffRatio(e1.ct, e2.ct)).toFixed(1) + " %  (the hash gives a full avalanche)"],
    ["One plaintext bit flipped: ciphertext bits that change", (bitDiffRatio(cFlip, cbytes) * 8 * cbytes.length).toFixed(0) + " bit(s)", (bitDiffRatio(eFlip.ct, e1.ct) * 8 * e1.ct.length).toFixed(0) + " bit(s)  (no diffusion: stream cipher)"],
    ["Same key, same message, encrypted twice", "identical ciphertexts: " + (cc === caesar(text, s) ? "yes" : "no"), "identical ciphertexts: " + (toHex(e1.ct) === toHex(e3.ct) ? "yes" : "no") + "  (fresh r each time)"]
  ];
  let h = "<tr><th>Property</th><th>Caesar</th><th>Toy ECC</th></tr>";
  rows.forEach(r => h += `<tr><td>${r[0]}</td><td>${r[1]}</td><td>${r[2]}</td></tr>`);
  $("cmpTab").innerHTML = h; $("cmpTab").style.display = "table";
  barChart($("cmpA"), cnt, { labels: ABC.split(""), every: 1, marks: pc });
  const bins = new Array(32).fill(0); bc.forEach((v, i) => bins[i >> 3] += v);
  barChart($("cmpB"), bins, { expected: e1.ct.length / 32, max: e1.ct.length / 32 * 2 });
}

