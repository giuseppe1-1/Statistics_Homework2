function barChart(svg, data, o) {
  o = o || {};
  const W = 340, H = 170, l = 36, r = 8, t = 10, b = 22;
  const max = o.max || Math.max(...data, ...(o.marks || [0]), o.expected || 0, 1e-9) * 1.15;
  const bw = (W - l - r) / data.length, fmt = o.fmt || (v => Math.round(v));
  let s = `<line x1="${l}" y1="${t}" x2="${l}" y2="${H - b}" class="ax"/><line x1="${l}" y1="${H - b}" x2="${W - r}" y2="${H - b}" class="ax"/>`;
  for (let i = 0; i <= 2; i++) {
    const y = H - b - (H - b - t) * i / 2;
    s += `<line x1="${l}" x2="${W - r}" y1="${y}" y2="${y}" class="gr"/><text x="${l - 4}" y="${y + 3}" font-size="10" font-family="Arial" class="tx" text-anchor="end">${fmt(max * i / 2)}</text>`;
  }
  data.forEach((v, i) => {
    const h = (H - b - t) * v / max;
    s += `<rect x="${l + i * bw + 1}" y="${H - b - h}" width="${Math.max(bw - 2, 1)}" height="${h}" fill="${o.color || "#3b9de0"}"/>`;
    if (o.labels && i % (o.every || 1) === 0) s += `<text x="${l + i * bw + bw / 2}" y="${H - 7}" font-size="9.5" font-family="Arial" class="tx" text-anchor="middle">${o.labels[i]}</text>`;
  });
  if (o.expected != null) { const y = H - b - (H - b - t) * o.expected / max; s += `<line x1="${l}" x2="${W - r}" y1="${y}" y2="${y}" stroke="#d62728" stroke-dasharray="4 3"/>`; }
  if (o.marks) o.marks.forEach((v, i) => { const y = H - b - (H - b - t) * v / max; s += `<line x1="${l + i * bw + 1}" x2="${l + i * bw + bw - 1}" y1="${y}" y2="${y}" class="tk" stroke-width="2"/>`; });
  svg.innerHTML = s;
}
